/// A city, its state, its telephone area code and the range of the first
/// five CEP digits its addresses use.
pub struct City {
    pub name: &'static str,
    pub uf: &'static str,
    pub ddd: u8,
    pub cep: (u32, u32),
    pub weight: u64,
}

const fn city(name: &'static str, uf: &'static str, ddd: u8, cep: (u32, u32), weight: u64) -> City {
    City {
        name,
        uf,
        ddd,
        cep,
        weight,
    }
}

